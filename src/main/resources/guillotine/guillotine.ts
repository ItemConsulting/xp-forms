import { forceArray } from "/lib/forms/arrays";
import type { ContentForm } from "/lib/forms/contents";
import { type FormPageRaw, getName } from "/lib/forms/form-utils";
import { getFieldNameFromConfig } from "/lib/forms/honeypot";
import { getPageJsonSchema, type JSONSchema } from "/lib/forms/json-schema";
import { getLocale } from "/lib/forms/locale";
import { getSpamPreventionType, getTurnstileSiteKey } from "/lib/forms/spam-prevention";
import { getSite, getSiteConfig } from "/lib/xp/content";
import { localize } from "/lib/xp/i18n";
import { apiUrl, pageUrl } from "/lib/xp/portal";

/*
  Builds on the types Guillotine generates for the Form content type, so that a frontend reads a form
  from `data` the way it is stored, with only what it needs to send it in added.

  Guillotine copies a form fragment into every place it is used, and gives each copy of its types a
  number, such as `no_item_forms_Form_Properties_2`. Here each fragment is an interface instead, which
  the field types that use it implement, and the fields that held a copy are pointed at one shared
  type. The numbered copies are still listed in the schema, since Guillotine registers every type it
  generates, but no field refers to them.

  On top of the stored data, a form gives the URL to send it to, its spam prevention, the JSON Schema
  of each page, and the problems an editor should fix. The name of a field falls back to one made
  from its label, the way the validators make it, and the texts an editor left empty are filled in
  with the defaults, in the form's language.
*/

// Generated by Guillotine
const OBJECT_TYPE_FORM = "no_item_forms_Form";
const OBJECT_TYPE_FORM_PAGES = "no_item_forms_Form_Pages";
const OBJECT_TYPE_FORM_SHOW_REVIEW_PAGE = "no_item_forms_Form_ShowReviewPage";
const OBJECT_TYPE_FORM_INPUT = "no_item_forms_Form_Input";
const OBJECT_TYPE_FORM_TEXTAREA = "no_item_forms_Form_Textarea";
const OBJECT_TYPE_FORM_RADIOBUTTONS = "no_item_forms_Form_Radiobuttons";
const OBJECT_TYPE_FORM_SELECT = "no_item_forms_Form_Select";
const OBJECT_TYPE_FORM_CHECKBOXES = "no_item_forms_Form_Checkboxes";
const OBJECT_TYPE_FORM_HIDDEN = "no_item_forms_Form_Hidden";

// One for each form fragment
const INTERFACE_FIELD_PROPS_COMMON = "no_item_forms_FieldPropsCommon";
const INTERFACE_FIELD_PROPS_INPUT = "no_item_forms_FieldPropsInput";
const INTERFACE_FIELD_PROPS_SELECT = "no_item_forms_FieldPropsSelect";
const INTERFACE_FIELD_PROPS_CHECKBOX = "no_item_forms_FieldPropsCheckbox";
const INTERFACE_OPTIONS = "no_item_forms_Options";

const OBJECT_TYPE_OPTION = "no_item_forms_Option";
const OBJECT_TYPE_FIELD_PROPS_INPUT_PROPERTIES = "no_item_forms_FieldPropsInputProperties";
const OBJECT_TYPE_FIELD_PROPS_SELECT_PROPERTIES = "no_item_forms_FieldPropsSelectProperties";
const OBJECT_TYPE_FIELD_PROPS_CHECKBOX_PROPERTIES = "no_item_forms_FieldPropsCheckboxProperties";
const OBJECT_TYPE_PLACEHOLDER = "no_item_forms_Placeholder";
const OBJECT_TYPE_INPUT_MODE = "no_item_forms_InputMode";
const OBJECT_TYPE_AUTOCOMPLETE = "no_item_forms_Autocomplete";
const OBJECT_TYPE_VALIDATION_REQUIRED = "no_item_forms_ValidationRequired";
const OBJECT_TYPE_VALIDATION_MIN_LENGTH = "no_item_forms_ValidationMinLength";
const OBJECT_TYPE_VALIDATION_MAX_LENGTH = "no_item_forms_ValidationMaxLength";
const OBJECT_TYPE_VALIDATION_PATTERN = "no_item_forms_ValidationPattern";
const OBJECT_TYPE_VALIDATION_MIN_ITEMS = "no_item_forms_ValidationMinItems";
const OBJECT_TYPE_VALIDATION_MAX_ITEMS = "no_item_forms_ValidationMaxItems";
const OBJECT_TYPE_FORM_SPAM_PREVENTION = "no_item_forms_FormSpamPrevention";

const ENUM_FIELD_PROPS_INPUT_PROPERTIES = `${OBJECT_TYPE_FIELD_PROPS_INPUT_PROPERTIES}_OptionEnum`;
const ENUM_FIELD_PROPS_SELECT_PROPERTIES = `${OBJECT_TYPE_FIELD_PROPS_SELECT_PROPERTIES}_OptionEnum`;
const ENUM_FIELD_PROPS_CHECKBOX_PROPERTIES = `${OBJECT_TYPE_FIELD_PROPS_CHECKBOX_PROPERTIES}_OptionEnum`;

const API_SUBMIT = "no.item.forms:submit";

// The `data` of a form puts the form's language in the local context of everything under it
type FormLocalContext = LocalContextRecord & {
  formLocale?: string;
};

type Env<Source, Args extends Record<string, unknown> = Record<string, unknown>> = DataFetchingEnvironment<
  Args,
  FormLocalContext,
  Source
>;

type OptionSource = { text?: string; value?: string };

type PropertiesSource = { _selected?: string | string[] };

export function extensions(graphQL: GraphQL): Extensions {
  const errorMessage = {
    type: graphQL.GraphQLString,
  };

  const interfaces = {
    common: graphQL.reference(INTERFACE_FIELD_PROPS_COMMON),
    input: graphQL.reference(INTERFACE_FIELD_PROPS_INPUT),
    select: graphQL.reference(INTERFACE_FIELD_PROPS_SELECT),
    checkbox: graphQL.reference(INTERFACE_FIELD_PROPS_CHECKBOX),
    options: graphQL.reference(INTERFACE_OPTIONS),
  };

  // The fields of an interface, as the generated types that implement it are changed to have them
  const fieldPropsCommonFields = {
    label: {
      type: graphQL.GraphQLString,
    },
    // The name the value is sent under, and the key of its validation errors. Made from the label
    // when the editor gave none.
    name: {
      type: graphQL.nonNull(graphQL.GraphQLString),
    },
    helpText: {
      type: graphQL.reference("RichText"),
      args: {
        processHtml: graphQL.reference("ProcessHtmlInput"),
      },
    },
    // The value the field starts with
    value: {
      type: graphQL.GraphQLString,
    },
  };

  // An option missing its text or value cannot be shown or sent, and is left out
  const optionsField = {
    type: graphQL.nonNull(graphQL.list(graphQL.nonNull(graphQL.reference(OBJECT_TYPE_OPTION)))),
    args: {},
  };

  const nameField = {
    type: fieldPropsCommonFields.name.type,
  };

  const longField = {
    type: graphQL.GraphQLInt,
  };

  return {
    interfaces: {
      [INTERFACE_FIELD_PROPS_COMMON]: {
        description: "The form fragment field-props-common: what every field but checkboxes and hidden has",
        fields: fieldPropsCommonFields,
      },
      [INTERFACE_FIELD_PROPS_INPUT]: {
        description: "The form fragment field-props-input: the properties of a text field or textarea",
        fields: {
          properties: {
            type: graphQL.reference(OBJECT_TYPE_FIELD_PROPS_INPUT_PROPERTIES),
          },
        },
      },
      [INTERFACE_FIELD_PROPS_SELECT]: {
        description: "The form fragment field-props-select: the properties of a select or radio buttons",
        fields: {
          properties: {
            type: graphQL.reference(OBJECT_TYPE_FIELD_PROPS_SELECT_PROPERTIES),
          },
        },
      },
      [INTERFACE_FIELD_PROPS_CHECKBOX]: {
        description: "The form fragment field-props-checkbox: the properties of checkboxes",
        fields: {
          properties: {
            type: graphQL.reference(OBJECT_TYPE_FIELD_PROPS_CHECKBOX_PROPERTIES),
          },
        },
      },
      [INTERFACE_OPTIONS]: {
        description:
          "The form fragment options: the options of a select or radio buttons. Checkboxes have options of the same shape.",
        fields: {
          options: optionsField,
        },
      },
    },
    enums: {
      [ENUM_FIELD_PROPS_INPUT_PROPERTIES]: {
        description: "Properties option enum.",
        values: {
          placeholder: "placeholder",
          inputMode: "inputMode",
          autocomplete: "autocomplete",
          validationRequired: "validationRequired",
          validationMinLength: "validationMinLength",
          validationMaxLength: "validationMaxLength",
          validationPattern: "validationPattern",
        },
      },
      [ENUM_FIELD_PROPS_SELECT_PROPERTIES]: {
        description: "Properties option enum.",
        values: {
          validationRequired: "validationRequired",
        },
      },
      [ENUM_FIELD_PROPS_CHECKBOX_PROPERTIES]: {
        description: "Properties option enum.",
        values: {
          validationRequired: "validationRequired",
          validationMinItems: "validationMinItems",
          validationMaxItems: "validationMaxItems",
        },
      },
    },
    types: {
      [OBJECT_TYPE_OPTION]: {
        description: "One option in a select, radio buttons or checkboxes field: the text shown and the value sent",
        fields: {
          text: {
            type: graphQL.nonNull(graphQL.GraphQLString),
          },
          value: {
            type: graphQL.nonNull(graphQL.GraphQLString),
          },
        },
      },
      [OBJECT_TYPE_FIELD_PROPS_INPUT_PROPERTIES]: {
        description: "Properties",
        fields: {
          _selected: {
            type: graphQL.nonNull(graphQL.list(graphQL.nonNull(graphQL.reference(ENUM_FIELD_PROPS_INPUT_PROPERTIES)))),
          },
          placeholder: {
            type: graphQL.reference(OBJECT_TYPE_PLACEHOLDER),
          },
          inputMode: {
            type: graphQL.reference(OBJECT_TYPE_INPUT_MODE),
          },
          autocomplete: {
            type: graphQL.reference(OBJECT_TYPE_AUTOCOMPLETE),
          },
          validationRequired: {
            type: graphQL.reference(OBJECT_TYPE_VALIDATION_REQUIRED),
          },
          validationMinLength: {
            type: graphQL.reference(OBJECT_TYPE_VALIDATION_MIN_LENGTH),
          },
          validationMaxLength: {
            type: graphQL.reference(OBJECT_TYPE_VALIDATION_MAX_LENGTH),
          },
          validationPattern: {
            type: graphQL.reference(OBJECT_TYPE_VALIDATION_PATTERN),
          },
        },
      },
      [OBJECT_TYPE_FIELD_PROPS_SELECT_PROPERTIES]: {
        description: "Properties",
        fields: {
          _selected: {
            type: graphQL.nonNull(graphQL.list(graphQL.nonNull(graphQL.reference(ENUM_FIELD_PROPS_SELECT_PROPERTIES)))),
          },
          validationRequired: {
            type: graphQL.reference(OBJECT_TYPE_VALIDATION_REQUIRED),
          },
        },
      },
      [OBJECT_TYPE_FIELD_PROPS_CHECKBOX_PROPERTIES]: {
        description: "Properties",
        fields: {
          _selected: {
            type: graphQL.nonNull(
              graphQL.list(graphQL.nonNull(graphQL.reference(ENUM_FIELD_PROPS_CHECKBOX_PROPERTIES))),
            ),
          },
          validationRequired: {
            type: graphQL.reference(OBJECT_TYPE_VALIDATION_REQUIRED),
          },
          validationMinItems: {
            type: graphQL.reference(OBJECT_TYPE_VALIDATION_MIN_ITEMS),
          },
          validationMaxItems: {
            type: graphQL.reference(OBJECT_TYPE_VALIDATION_MAX_ITEMS),
          },
        },
      },
      [OBJECT_TYPE_PLACEHOLDER]: {
        description: "Placeholder",
        fields: {
          placeholder: {
            type: graphQL.GraphQLString,
          },
        },
      },
      [OBJECT_TYPE_INPUT_MODE]: {
        description: "Input mode",
        fields: {
          // The value of the input's inputmode attribute, such as "numeric"
          inputmode: {
            type: graphQL.GraphQLString,
          },
        },
      },
      [OBJECT_TYPE_AUTOCOMPLETE]: {
        description: "Autocomplete",
        fields: {
          // The value of the input's autocomplete attribute, such as "email"
          autocomplete: {
            type: graphQL.GraphQLString,
          },
        },
      },
      [OBJECT_TYPE_VALIDATION_REQUIRED]: {
        description: "Required",
        fields: {
          errorMessage,
        },
      },
      [OBJECT_TYPE_VALIDATION_MIN_LENGTH]: {
        description: "Min length",
        fields: {
          minLength: longField,
          errorMessage,
        },
      },
      [OBJECT_TYPE_VALIDATION_MAX_LENGTH]: {
        description: "Max length",
        fields: {
          maxLength: longField,
          errorMessage,
        },
      },
      [OBJECT_TYPE_VALIDATION_PATTERN]: {
        description: "Pattern",
        fields: {
          regexString: {
            type: graphQL.GraphQLString,
          },
          errorMessage,
        },
      },
      [OBJECT_TYPE_VALIDATION_MIN_ITEMS]: {
        description: "Min items",
        fields: {
          minItems: longField,
          errorMessage,
        },
      },
      [OBJECT_TYPE_VALIDATION_MAX_ITEMS]: {
        description: "Max items",
        fields: {
          maxItems: longField,
          errorMessage,
        },
      },
      [OBJECT_TYPE_FORM_SPAM_PREVENTION]: {
        description:
          "The spam prevention of the form's site, which the frontend renders and sends along with the values",
        fields: {
          // "turnstile", "honeypot", or "none" when the form has no site
          type: {
            type: graphQL.nonNull(graphQL.GraphQLString),
          },
          // The key to render the Turnstile widget with. Null unless the type is "turnstile".
          turnstileSiteKey: {
            type: graphQL.GraphQLString,
          },
          // The name of the field to leave empty and hidden from people. Null unless the type is "honeypot".
          honeypotFieldName: {
            type: graphQL.GraphQLString,
          },
        },
      },
    },
    // No field returns one of the interfaces, so GraphQL never has to tell which type an object is.
    // It requires a type resolver for every interface all the same.
    typeResolvers: {
      [INTERFACE_FIELD_PROPS_COMMON]: unresolvableType,
      [INTERFACE_FIELD_PROPS_INPUT]: unresolvableType,
      [INTERFACE_FIELD_PROPS_SELECT]: unresolvableType,
      [INTERFACE_FIELD_PROPS_CHECKBOX]: unresolvableType,
      [INTERFACE_OPTIONS]: unresolvableType,
    },
    creationCallbacks: {
      [OBJECT_TYPE_FORM]: (params) => {
        params.addFields({
          // Where to post the values of every page, as form parameters, once the visitor sends the
          // form. Absolute, on the form's site, with the form's id in the path.
          submitUrl: {
            type: graphQL.nonNull(graphQL.GraphQLString),
          },
          // What the submit API checks before it sends the form, as chosen in the site's config
          spamPrevention: {
            type: graphQL.nonNull(graphQL.reference(OBJECT_TYPE_FORM_SPAM_PREVENTION)),
          },
        });
      },
      [OBJECT_TYPE_FORM_PAGES]: (params) => {
        params.modifyFields({
          submitButtonText: {
            type: graphQL.nonNull(graphQL.GraphQLString),
          },
        });
        params.addFields({
          // A JSON Schema (draft 2020-12) of the values on the page, keyed by field name. Validate the
          // values once they are normalized: the first non-empty value as a string, every non-empty
          // value as an array for checkboxes, and a field without one left out. The message for each
          // rule that fails is in the field's `errorMessages`, keyed by keyword, `required` included.
          // A `pattern` is an ECMAScript regular expression without the "u" flag. A pattern with flags
          // is in `regexp` instead, as `{ pattern, flags }`, the way the "regexp" keyword of
          // ajv-keywords reads it.
          validationSchema: {
            type: graphQL.nonNull(graphQL.Json),
          },
        });
      },
      [OBJECT_TYPE_FORM_SHOW_REVIEW_PAGE]: (params) => {
        params.modifyFields({
          title: {
            type: graphQL.nonNull(graphQL.GraphQLString),
          },
          submitButtonText: {
            type: graphQL.nonNull(graphQL.GraphQLString),
          },
        });
      },
      [OBJECT_TYPE_FORM_INPUT]: (params) => {
        params.setInterfaces([interfaces.common, interfaces.input]);
        params.modifyFields({
          name: nameField,
          properties: {
            type: graphQL.reference(OBJECT_TYPE_FIELD_PROPS_INPUT_PROPERTIES),
          },
        });
      },
      [OBJECT_TYPE_FORM_TEXTAREA]: (params) => {
        params.setInterfaces([interfaces.common, interfaces.input]);
        params.modifyFields({
          name: nameField,
          properties: {
            type: graphQL.reference(OBJECT_TYPE_FIELD_PROPS_INPUT_PROPERTIES),
          },
          // The height of the textarea, in lines. Null when the editor set none.
          rows: longField,
          // The width of the textarea, in characters. Null when the editor set none.
          cols: longField,
        });
      },
      [OBJECT_TYPE_FORM_RADIOBUTTONS]: (params) => {
        params.setInterfaces([interfaces.common, interfaces.select, interfaces.options]);
        params.modifyFields({
          name: nameField,
          properties: {
            type: graphQL.reference(OBJECT_TYPE_FIELD_PROPS_SELECT_PROPERTIES),
          },
          options: optionsField,
        });
      },
      [OBJECT_TYPE_FORM_SELECT]: (params) => {
        params.setInterfaces([interfaces.common, interfaces.select, interfaces.options]);
        params.modifyFields({
          name: nameField,
          properties: {
            type: graphQL.reference(OBJECT_TYPE_FIELD_PROPS_SELECT_PROPERTIES),
          },
          options: optionsField,
        });
      },
      // Checkboxes repeat the fields of field-props-common rather than use it, since they start with
      // several values
      [OBJECT_TYPE_FORM_CHECKBOXES]: (params) => {
        params.setInterfaces([interfaces.checkbox, interfaces.options]);
        params.modifyFields({
          name: nameField,
          properties: {
            type: graphQL.reference(OBJECT_TYPE_FIELD_PROPS_CHECKBOX_PROPERTIES),
          },
          options: optionsField,
        });
      },
      [OBJECT_TYPE_FORM_HIDDEN]: (params) => {
        params.modifyFields({
          name: nameField,
        });
      },
    },
    resolvers: {
      [OBJECT_TYPE_FORM]: {
        // The data as Guillotine gives it, with the form's language in the local context, for the
        // defaults under it. Guillotine is served outside the form's site, so the language is not
        // in the request.
        data: (env: Env<ContentForm>) =>
          graphQL.createDataFetcherResult<ContentForm["data"], FormLocalContext>({
            data: __.toScriptValue(env.source.data),
            localContext: {
              formLocale: getLocale({ content: env.source, site: getSite({ key: env.source._id }) }),
            },
            parentLocalContext: env.localContext,
          }),
        // Guillotine is served from the root of the project, where the API is not mounted, so the URL
        // is made from the form's site instead
        submitUrl: (env: Env<ContentForm>) => {
          const site = getSite({ key: env.source._id });

          return apiUrl({
            api: API_SUBMIT,
            path: env.source._id,
            type: "absolute",
            baseUrl: site ? pageUrl({ id: site._id, type: "absolute" }) : undefined,
          });
        },
        spamPrevention: (env: Env<ContentForm>) => {
          const siteConfig = getFormSiteConfig(getSite({ key: env.source._id }));
          const type = getSpamPreventionType(siteConfig);

          return {
            type,
            // Null when the site has none, and the form cannot be sent
            turnstileSiteKey: type === "turnstile" ? (getTurnstileSiteKey(siteConfig) ?? null) : null,
            honeypotFieldName: type === "honeypot" ? getFieldNameFromConfig(siteConfig) : null,
          };
        },
      },
      [OBJECT_TYPE_FORM_PAGES]: {
        submitButtonText: (env: Env<FormPageRaw>) =>
          env.source.submitButtonText ?? localize({ key: "part.formView.submit", locale: getFormLocale(env) }),
        validationSchema: (env: Env<FormPageRaw>): JSONSchema => getPageJsonSchema(env.source, getFormLocale(env)),
      },
      [OBJECT_TYPE_FORM_SHOW_REVIEW_PAGE]: {
        title: (env: Env<{ title?: string }>) =>
          env.source.title ?? localize({ key: "part.formView.reviewPageTitle", locale: getFormLocale(env) }),
        submitButtonText: (env: Env<{ submitButtonText?: string }>) =>
          env.source.submitButtonText ??
          localize({ key: "part.formView.reviewPageButtonText", locale: getFormLocale(env) }),
      },
      // A resolver of an interface is used by every type that implements it
      [INTERFACE_FIELD_PROPS_COMMON]: {
        name: (env: Env<{ label?: string; name?: string }>) => getName(env.source),
      },
      [INTERFACE_OPTIONS]: {
        options: (env: Env<{ options?: OptionSource | OptionSource[] }>) =>
          forceArray(env.source.options).filter((option) => option.value && option.text),
      },
      [OBJECT_TYPE_FORM_CHECKBOXES]: {
        name: (env: Env<{ label?: string; name?: string }>) => getName(env.source),
      },
      [OBJECT_TYPE_FORM_HIDDEN]: {
        name: (env: Env<{ name?: string }>) => getName(env.source),
      },
      // An option set with several options selected is stored with a single value when only one is
      [OBJECT_TYPE_FIELD_PROPS_INPUT_PROPERTIES]: {
        _selected: (env: Env<PropertiesSource>) => forceArray(env.source._selected),
      },
      [OBJECT_TYPE_FIELD_PROPS_SELECT_PROPERTIES]: {
        _selected: (env: Env<PropertiesSource>) => forceArray(env.source._selected),
      },
      [OBJECT_TYPE_FIELD_PROPS_CHECKBOX_PROPERTIES]: {
        _selected: (env: Env<PropertiesSource>) => forceArray(env.source._selected),
      },
    },
  };
}

function getFormLocale(env: Env<unknown>): string {
  return env.localContext.formLocale ?? getLocale({});
}

function getFormSiteConfig(site: { _id: string } | null): XP.SiteConfig | null {
  return site ? getSiteConfig<XP.SiteConfig>({ key: site._id, applicationKey: app.name }) : null;
}

function unresolvableType(): never {
  throw new Error("No field returns a form fragment interface, so its type is never resolved");
}
